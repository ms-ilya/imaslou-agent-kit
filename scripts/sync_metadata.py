#!/usr/bin/env python3
# ABOUTME: Synchronizes Codex packaging and bundled runtime guidance from shared plugin sources.

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def generated_files(root=ROOT):
    catalogue = json.loads((root / '.claude-plugin/marketplace.json').read_text())
    entries = []
    runtime = (root / 'docs/runtime.md').read_text()
    for entry in catalogue['plugins']:
        plugin = root / entry['source']
        manifest = json.loads((plugin / '.claude-plugin/plugin.json').read_text())
        title = manifest['name'].replace('-', ' ').title().replace('Ios', 'iOS')
        codex = dict(manifest)
        codex['skills'] = './skills/'
        codex['interface'] = {
            'displayName': title,
            'shortDescription': entry['description'].split('. ')[0].rstrip('.'),
            'longDescription': manifest['description'],
            'developerName': 'Ilya Maslau',
            'category': 'Productivity',
        }
        yield plugin / '.codex-plugin/plugin.json', json.dumps(codex, indent=2, ensure_ascii=False) + '\n'
        yield plugin / 'references/runtime.md', runtime
        for skill in sorted((plugin / 'skills').glob('*/SKILL.md')):
            frontmatter = skill.read_text().split('---', 2)[1]
            explicit = bool(re.search(r'^disable-model-invocation: true\s*$', frontmatter, re.M))
            yield skill.parent / 'agents/openai.yaml', (
                '# Generated by scripts/sync_metadata.py from SKILL.md.\n'
                'policy:\n'
                f'  allow_implicit_invocation: {str(not explicit).lower()}\n'
            )
        entries.append({
            'name': entry['name'],
            'source': {'source': 'local', 'path': entry['source']},
            'policy': {'installation': 'AVAILABLE', 'authentication': 'ON_INSTALL'},
            'category': 'Productivity',
        })
    yield root / '.agents/plugins/marketplace.json', json.dumps({
        'name': catalogue['name'], 'plugins': entries,
    }, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Report drift without writing files')
    args = parser.parse_args()
    stale = []
    for path, content in generated_files():
        if path.exists() and path.read_text() == content:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check and stale:
        print('Generated files need synchronization:\n' + '\n'.join(stale))
        return 1
    print(f'Metadata {"checked" if args.check else "synchronized"}: {len(stale)} file(s) {"stale" if args.check else "updated"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
